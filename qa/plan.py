# The game plan: every setup choice is honoured once the game runs. Own static server on :8721 (local storage mode).
# python3 qa/plan.py
import os, sys, subprocess, time
from playwright.sync_api import sync_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); PORT = 8721
srv = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT), "--directory", os.path.join(ROOT, "worker/public")], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
fails = []
def check(name, cond, extra=""):
    print(("PASS " if cond else "FAIL ") + name + (" — " + str(extra)[:300] if extra and not cond else ""))
    if not cond: fails.append(name)
NAMES = ["Annie", "Ryan", "Tom", "Sophie", "Marcus", "Priya", "Jess", "Oliver", "Hannah", "Dev"]
try:
    with sync_playwright() as p:
        b = p.chromium.launch(); errs = []
        ctx = b.new_context(viewport={"width": 390, "height": 844}); h = ctx.new_page(); h.on("pageerror", lambda e: errs.append(str(e)))
        h.goto(f"http://localhost:{PORT}/play.html#host"); h.wait_for_timeout(1200)
        E = h.evaluate; body = lambda: h.inner_text("#host")
        def game(rules, n=10):
            E("()=>{try{localStorage.clear()}catch(e){};state=null;hist=[]}")
            E("(a)=>startGame({names:a[0],cloaks:2,title:'',host:'Sam',potUnit:'£',potCap:2000,prize:'x',hours:4,pin:'1',rules:a[1]})", [NAMES[:n], rules])
            E("()=>act(s=>{s.players.forEach((p,i)=>p.role=[0,1].includes(i)?'cloak':'candle');s.phase='day'})"); h.wait_for_timeout(150)
        # setup screen: the accordion writes the plan into the game
        h.evaluate("(a)=>{setupDraft=Object.assign(SETUP0(),{names:a,pin:'1111'});renderHost()}", "\n".join(NAMES))
        E("()=>{wSet('kill','murder');wSet('ghosts',false);wSet('blade',false);wSet('champion',false);wSet('rounds',4);wSet('perRound',2);poolD('quiz');poolD('statue')}")
        check("the blade and the Champion are separate choices", E("()=>{wSet('champion',true);const c=setupDraft.champion&&!setupDraft.blade;wSet('champion',false);return c}"))
        E("()=>submitSetup()"); h.wait_for_timeout(300)
        r = E("()=>state.rules")
        check("setup choices land in the game's rules", r["kill"] == "murder" and r["ghosts"] is False and r["blade"] is False and r["champion"] is False and r["rounds"] == 4 and r["perRound"] == 2 and "quiz" not in r["pool"], r)
        check("the plan only deals missions from the pool, and never the Statue without Ghosts", E("()=>state.plan.length>0 && state.plan.every(k=>state.rules.pool.includes(k)) && !state.plan.includes('statue')"), E("()=>state.plan"))
        # murder, no Ghosts
        game({"kill": "murder", "ghosts": False})
        E("()=>{act(s=>{s.phase='table';s.table=newTable()});exile(state.players[9].id);if(ask)askGo();revealRole()}")
        check("no Ghost lore or verdicts without Ghosts", "ghost" not in body().lower(), body()[:300])
        E("()=>{startNight();act(s=>{s.night.mode='murder'});beginNight();act(s=>{s.night.victimId=s.players[5].id})}")
        sc = E("()=>nightScript(state.night,state).map(l=>norm(l).tv).join(' | ')")
        check("murder night: the victim is told to leave the table now, and there are no Ghosts to join", "leave the table now" in sc and "Thank you for playing" in sc and "Ghost" not in sc, sc)
        check("murder night never says poison", "poison" not in sc.lower() and "poison" not in body().lower())
        E("()=>{act(s=>{s.night.step=nightScript(s.night,s).length-1});finishNight()}")
        check("dawn, murder: the host is told about the empty chair", "empty chair" in body(), body()[:400])
        E("()=>act(s=>{s.morning.revealed=true})")
        check("no last words for the murdered — they've already gone", "Last words" not in body())
        # poison, Ghosts on: last words
        game({"kill": "poison", "ghosts": True})
        E("()=>{startNight();act(s=>{s.night.mode='murder';s.night.victimId=s.players[5].id});beginNight();act(s=>{s.night.step=nightScript(s.night,s).length-1});finishNight();act(s=>{s.morning.revealed=true})}")
        check("poison: announced at dawn, with last words", "Last words" in body() and "poison" in body().lower())
        # rounds and missions per round
        game({"rounds": 2, "perRound": 2})
        check("rounds a table this size can't play are clamped: 2 for ten players becomes 4", E("()=>state.rules.rounds") == 4, E("()=>state.rules.rounds"))
        E("()=>{pickMission(nextPlanned(state));startMission();startMission();act(s=>finishPlay(s));endMission();act(s=>{if(s.shieldCard)s.shieldCard.step=9})}")
        check("two missions a round: after the first, the plan says another", "Next Trial" in h.inner_text(".foot"), h.inner_text(".foot"))
        E("()=>{nextRound();nextRound();nextRound()}")
        check("a fixed four rounds makes round 4 the final", E("()=>state.round===4 && state.finalRound===4"))
        # prizes by the plan
        game({"shield": "off", "blade": False})
        E("()=>pickMission('quiz')")
        check("shields off, blade off: the mission carries neither", E("()=>state.mission.win==='none' && state.mission.dag==='none'"), E("()=>[state.mission.win,state.mission.dag]"))
        game({"shield": "public", "blade": True, "champion": True})
        check("ten players, four rounds: the blade comes in round 2, the Champion in round 3", E("()=>[onceRound(state,'blade'),onceRound(state,'champion')]") == [2, 3])
        E("()=>pickMission('charades')")
        check("round 1: a shield only, no blade yet", E("()=>state.mission.win==='public' && state.mission.dag==='none'"), E("()=>[state.mission.win,state.mission.dag]"))
        E("()=>{act(s=>{s.phase='day';s.mission=null;s.round=2});pickMission('charades')}")
        check("round 2: the blade takes the shield's place on a mission without rounds", E("()=>state.mission.win==='none' && state.mission.dag==='public'"), E("()=>[state.mission.win,state.mission.dag]"))
        E("()=>{act(s=>{s.mission.stage='done';s.mission.winId=s.players[5].id});endMission()}")
        check("winning the blade marks it given for the rest of the game", E("()=>state.gave.blade===2 && state.champion && state.champion.id===state.players[5].id"), E("()=>state.gave"))
        E("()=>{act(s=>{s.gave={blade:2};s.phase='day';s.mission=null;s.round=3});pickMission('charades')}")
        check("round 3: the Champion — a public shield and the blade together", E("()=>state.mission.win==='public' && state.mission.dag==='with'"), E("()=>[state.mission.win,state.mission.dag]"))
        E("()=>{act(s=>{s.gave={blade:2,champion:3};s.phase='day';s.mission=null;s.round=4});pickMission('charades')}")
        check("once each: after the blade and the Champion, only shields", E("()=>state.mission.win==='public' && state.mission.dag==='none'"), E("()=>[state.mission.win,state.mission.dag]"))
        check("…and the brief offers no blade to set by hand", not E("()=>bladeOk(state,state.mission)"))
        game({"shield": "mix", "blade": True})
        E("()=>pickMission('quiz')")
        check("mixed shields, round 1: a round-by-round mission hides its shield, no blade yet", E("()=>state.mission.win==='secret' && state.mission.dag==='none'"), E("()=>[state.mission.win,state.mission.dag]"))
        E("()=>{act(s=>{s.phase='day';s.mission=null;s.round=2});pickMission('quiz')}")
        check("…round 2: a hidden shield and a hidden blade", E("()=>state.mission.win==='secret' && state.mission.dag==='secret'"), E("()=>[state.mission.win,state.mission.dag]"))
        E("()=>{act(s=>{s.phase='day';s.mission=null;s.round=3});pickMission('quiz')}")
        check("…an unclaimed blade comes round again on the next mission", E("()=>state.mission.dag!=='none'"), E("()=>[state.mission.win,state.mission.dag]"))
        game({"dilemma": True})
        check("the Dilemma: offered until it's played once", E("()=>{const a=dilemmaFree(state);act(s=>{s.done.dilemma=1});return a&&!dilemmaFree(state)}"))
        # a final that opens with six (a shield held on the last night): one vote to five, then one more mission, where the Witness is won
        game({"witness": True})
        E("()=>act(s=>{s.players.forEach((p,i)=>{p.alive=i<6;p.role=i===0?'cloak':'candle'});s.round=4;s.finalRound=4;s.plan=['likely','quiz'];s.planAt=0;s.phase='table';s.table=newTable()})")
        E("()=>{toExile();exile(state.players[5].id);if(ask)askGo();revealRole()}"); h.wait_for_timeout(200)
        check("final at five after a vote: the host is offered one more mission, not another vote", "Five left: one more Trial" in body()
 and "Another vote" not in body(), body()[-300:])
        E("()=>fiveMission()"); h.wait_for_timeout(100)
        check("…it's a mission that can carry a prize (never the icebreaker)", E("()=>state.phase==='day' && nextPlanned(state)!=='likely'"), E("()=>nextPlanned(state)"))
        E("()=>pickMission(nextPlanned(state))")
        check("…and it offers the Witness (five left, one Cloak)", E("()=>state.mission.witnessOffer===true"))
        E("()=>{act(s=>{s.mission=null;s.phase='table';s.table=newTable()})}")
        E("()=>{toExile();exile(state.players[4].id);if(ask)askGo();revealRole()}"); h.wait_for_timeout(200)
        check("…then the last vote leaves four and goes to End or Exile", "Trust or Doubt" in body(), body()[-300:])
        game({"witness": False})
        E("()=>{act(s=>{s.players.forEach((p,i)=>{p.alive=i<5;p.role=i===0?'cloak':'candle'})});pickMission('quiz')}")
        check("Witness off: never offered, even at five with one Cloak", E("()=>!state.mission.witnessOffer") and "Witness" not in body())
        # the night, by the plan
        game({"convert": False, "bargain": True})
        E("()=>{act(s=>{s.players[1].role='candle'});startNight()}")
        check("convert off: a lone Cloak gets the Bargain instead", E("()=>state.night.mode") == "bargain")
        check("…and only the kinds switched on are offered", not E("()=>[...document.querySelectorAll('#host button')].some(b=>b.textContent.trim()==='Whisper')") and E("()=>[...document.querySelectorAll('#host button')].some(b=>b.textContent.trim()==='Last Offer')"))
        game({"quests": True})
        E("()=>startNight()")
        check("side-quests on: one is already chosen for tonight", E("()=>!!state.night.quest"))
        # dinner by the plan
        game({"dinnerAfter": 2})
        E("()=>{startNight();act(s=>{s.night.mode='murder';s.night.victimId=s.players[5].id});beginNight();act(s=>{s.night.step=nightScript(s.night,s).length-1});finishNight();act(s=>{s.morning.revealed=true})}")
        check("dinner after round 2: not offered after round 1", "Dinner now" not in h.inner_text(".foot"))
        E("()=>{nextRound();startNight();act(s=>{s.night.mode='murder';s.night.victimId=s.players[6].id});beginNight();act(s=>{s.night.step=nightScript(s.night,s).length-1});finishNight();act(s=>{s.morning.revealed=true})}")
        check("…and served after round 2", "Dinner now" in h.inner_text(".foot"), h.inner_text(".foot"))
        # the TV in a murder game
        game({"kill": "murder"})
        tv = ctx.new_page(); tv.set_viewport_size({"width": 1920, "height": 1080}); tv.goto(f"http://localhost:{PORT}/play.html"); tv.wait_for_timeout(1500)
        t = tv.evaluate("()=>{const s=publicView(state);s.tvRules=true;s.phase='lobby';const d=document.createElement('div');d.innerHTML=tvView(s).html;return d.textContent}")
        check("TV rules card: murder, no poison", "murder" in t and "poison" not in t.lower(), t)
        check("no page errors", not errs, errs[:3])
        b.close()
finally:
    srv.terminate()
print("RESULT:", "CLEAN" if not fails else "PROBLEMS " + str(len(fails))); sys.exit(1 if fails else 0)
