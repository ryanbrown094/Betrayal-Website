const out = {}, code = "K7Q2XM", v = (k, pid) => (out[k] = { code, site: "thebetrayal.co.uk", host: viewFor(s, pid, now), tv: viewFor(s, null, now) });
v("lobby", ids[0]);
act(s, ids[0], { a: "start" }, now, ctx); v("oath", ids[1]);
